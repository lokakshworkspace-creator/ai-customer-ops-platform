"""POST /api/v1/chat: one user message in, one reply out.

The LLM proposes, the backend decides: every action the assistant takes runs through the tool
executor (see app/agent/orchestrator.py). This endpoint only authenticates the caller, passes the
message on, and returns what the orchestrator produced. No business logic lives here.
"""

import uuid
from typing import Annotated

from fastapi import APIRouter, Depends, Request
from fastapi.responses import JSONResponse
from pydantic import BaseModel, ConfigDict, StringConstraints
from sqlalchemy.ext.asyncio import AsyncSession

from app.agent.orchestrator import AgentError, Orchestrator
from app.api.deps import CurrentUser, get_orchestrator, get_session
from app.core.config import get_settings
from app.policy.types import Actor

router = APIRouter(prefix="/api/v1/chat", tags=["chat"])

REPLAY_HEADER = "Idempotent-Replayed"
HARD_MAX_CHARS = 10_000  # memory guard; the real limit is settings.agent_max_message_chars


class ChatRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    message: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=HARD_MAX_CHARS)
    ]
    message_id: uuid.UUID  # generated by the client, once per message; resending it is safe
    conversation_id: uuid.UUID | None = None  # omit to start a conversation


DESCRIPTION = """
Send one message to the assistant.

* `message_id` is a UUID **you generate for each message**. Sending the same `message_id` again
  (a retry after a timeout, a double click) returns the **stored response** with the header
  `Idempotent-Replayed: true`; the assistant and its tools are not run a second time, so a refund
  can never be requested twice by a retry.
* `conversation_id` is returned by the first reply. An unknown id, or one that belongs to someone
  else, is `404`.
* The reply's `tool_results` are built by the backend from what the tools actually did; the
  `reply` text is the model's wording. If they disagree, `tool_results` is right.
* `status`: `completed`, `waiting_approval` (a person must approve a refund; poll
  `GET /api/v1/workflows/{workflow_id}`), `escalated` (a limit was hit and a ticket was opened) or
  `failed` (the assistant stopped after part of the request was carried out).
* `llm` says whether the reply came from the `gemini` model or the built-in `fake` one.
* Errors: `404` conversation not found; `409` the previous message is still being processed (or
  the `message_id` belongs to another conversation); `429` too many messages this hour; `503` the
  assistant is unavailable (nothing was done; the same `message_id` may be sent again).
"""


@router.post("", description=DESCRIPTION)
async def chat(
    request: Request,
    body: ChatRequest,
    user: CurrentUser,
    session: Annotated[AsyncSession, Depends(get_session)],
    orchestrator: Annotated[Orchestrator, Depends(get_orchestrator)],
) -> JSONResponse:
    # Copy what we need out of the ORM user now: the orchestrator commits and rolls back on this
    # session, and a rollback expires every loaded object.
    actor = Actor(id=user.id, role=user.role)
    limit = get_settings().agent_max_message_chars
    if len(body.message) > limit:
        return JSONResponse(
            {
                "detail": f"Message too long (at most {limit} characters).",
                "code": "MESSAGE_TOO_LONG",
            },
            status_code=422,
        )
    try:
        result = await orchestrator.handle_message(
            session,
            actor=actor,
            request_id=getattr(request.state, "request_id", None),
            text=body.message,
            message_id=body.message_id,
            conversation_id=body.conversation_id,
        )
    except AgentError as exc:
        return JSONResponse({"detail": exc.message, "code": exc.code}, status_code=exc.http_status)
    headers = {REPLAY_HEADER: "true"} if result.replayed else {}
    return JSONResponse(result.response, headers=headers)
